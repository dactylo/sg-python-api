#!/usr/bin/env bash

set -euo pipefail

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
REPO_ROOT=$(git -C "$SCRIPT_DIR" rev-parse --show-toplevel)
RESULTS_FILE="$REPO_ROOT/dist/artifact-results.md"

if [[ $# -eq 0 ]]; then
    OUTPUT_ROOT="$REPO_ROOT/dist/validated-artifacts"
elif [[ $# -eq 2 && $1 == '--output-dir' && -n $2 ]]; then
    OUTPUT_ROOT=$2
else
    printf 'Usage: %s [--output-dir PATH]\n' "$0" >&2
    exit 2
fi
OUTPUT_ROOT=$(python -c \
    'from pathlib import Path; import sys; print(Path(sys.argv[1]).resolve())' "$OUTPUT_ROOT")
if ! git -C "$REPO_ROOT" check-ignore --no-index --quiet -- "$OUTPUT_ROOT"; then
    printf 'Artifact output directory must be VCS-ignored: %s\n' "$OUTPUT_ROOT" >&2
    exit 1
fi
if [[ -e $OUTPUT_ROOT || -L $OUTPUT_ROOT ]]; then
    printf 'Artifact output path already exists: %s\n' "$OUTPUT_ROOT" >&2
    exit 1
fi

ARTIFACT_SHA256='pending'
ARTIFACT_NAME='pending'
CANDIDATE_COMMIT='pending'
HATCHLING_VERSION='pending'
HTTPX2_VERSION='pending'
INSTALLER_VERSION='pending'
PYTHON_VERSION='pending'
PYTEST_VERSION='pending'
PRESERVED_SDIST_PATH='pending'
PRESERVED_SDIST_WHEEL_PATH='pending'
PRESERVED_SOURCE_WHEEL_PATH='pending'
SDIST_SHA256='pending'
SDIST_NAME='pending'
SDIST_WHEEL_SHA256='pending'
SDIST_WHEEL_NAME='pending'
STAGE='initialization'
STATUS='FAIL'
URLLIB3_VERSION='pending'
ANYIO_VERSION='pending'
WORK_ROOT=''
REPORT_ENABLED=0
OUTPUT_CREATED=0

declare -a CHECK_RESULTS=()

cleanup() {
    if [[ $STATUS != 'PASS' && $OUTPUT_CREATED -eq 1 ]]; then
        rm -rf -- "$OUTPUT_ROOT"
    fi
    if [[ -n ${WORK_ROOT:-} && -d $WORK_ROOT ]]; then
        rm -rf -- "$WORK_ROOT"
    fi
}

write_report() {
    {
        printf '%s\n' '<!-- Generated by scripts/validate_artifacts.sh. Do not edit by hand. -->'
        printf '\n# Artifact validation results\n\n'
        printf -- '- Status: %s\n' "$STATUS"
        printf -- '- Candidate commit: `%s`\n' "$CANDIDATE_COMMIT"
        printf '\n## Artifacts\n\n'
        printf -- '- Source wheel: `%s`\n' "$ARTIFACT_NAME"
        printf -- '- Source wheel SHA256: `%s`\n' "$ARTIFACT_SHA256"
        printf -- '- Source distribution: `%s`\n' "$SDIST_NAME"
        printf -- '- Source distribution SHA256: `%s`\n' "$SDIST_SHA256"
        printf -- '- Sdist-derived wheel: `%s`\n' "$SDIST_WHEEL_NAME"
        printf -- '- Sdist-derived wheel SHA256: `%s`\n' "$SDIST_WHEEL_SHA256"
        printf -- '- Preserved source wheel: `%s`\n' "$PRESERVED_SOURCE_WHEEL_PATH"
        printf -- '- Preserved source distribution: `%s`\n' "$PRESERVED_SDIST_PATH"
        printf -- '- Preserved sdist-derived wheel: `%s`\n' "$PRESERVED_SDIST_WHEEL_PATH"
        printf '\n## Tool versions\n\n'
        printf -- '- Python: `%s`\n' "$PYTHON_VERSION"
        printf -- '- anyio: `%s`\n' "$ANYIO_VERSION"
        printf -- '- hatchling: `%s`\n' "$HATCHLING_VERSION"
        printf -- '- httpx2: `%s`\n' "$HTTPX2_VERSION"
        printf -- '- installer: `%s`\n' "$INSTALLER_VERSION"
        printf -- '- pytest: `%s`\n' "$PYTEST_VERSION"
        printf -- '- urllib3: `%s`\n' "$URLLIB3_VERSION"
        printf '\n## Build command compatibility\n\n'
        printf '%s\n' \
            '- Hatchling uses repeated `-t` options in this environment. Its comma-separated' \
            '  `-t wheel,sdist` form is invalid, so validation uses `-t wheel -t sdist`.'
        printf '\n## Checks\n\n'
        if [[ ${#CHECK_RESULTS[@]} -eq 0 ]]; then
            printf '%s\n' 'No artifact validation checks have completed.'
        else
            local entry
            local result
            local description
            for entry in "${CHECK_RESULTS[@]}"; do
                result=${entry%%|*}
                description=${entry#*|}
                printf -- '- %s: %s\n' "$result" "$description"
            done
        fi
    } >"$RESULTS_FILE"

    python - "$RESULTS_FILE" <<'PY'
from pathlib import Path
import sys

Path(sys.argv[1]).read_text(encoding='ascii')
PY
}

record_check() {
    local result=$1
    local description=$2
    CHECK_RESULTS+=("$result|$description")
    write_report
}

finish() {
    local exit_code=$?
    trap - EXIT INT TERM
    set +e
    if [[ $REPORT_ENABLED -eq 1 ]]; then
        if [[ $exit_code -eq 0 && $STATUS == 'PASS' ]]; then
            write_report
        else
            STATUS='FAIL'
            CHECK_RESULTS+=("FAIL|$STAGE")
            write_report
        fi
    fi
    cleanup
    exit "$exit_code"
}

require_module() {
    local module=$1
    local package=$2
    if ! python -c "import $module" >/dev/null 2>&1; then
        printf 'Missing required package: %s (Python module %s)\n' \
            "$package" "$module" >&2
        exit 1
    fi
}

distribution_version() {
    python -c \
        'import importlib.metadata, sys; print(importlib.metadata.version(sys.argv[1]))' "$1"
}

sha256_file() {
    python -c \
        'import hashlib, pathlib, sys; print(hashlib.sha256(pathlib.Path(sys.argv[1]).read_bytes()).hexdigest())' \
        "$1"
}

report_artifact_path() {
    python -c \
        'from pathlib import Path; import sys; artifact = Path(sys.argv[1]).resolve(); root = Path(sys.argv[2]).resolve(); print(artifact.relative_to(root).as_posix() if artifact.is_relative_to(root) else artifact)' \
        "$1" "$REPO_ROOT"
}

trap finish EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

STAGE='clean tracked candidate check'
if [[ -n $(
    git -C "$REPO_ROOT" status --porcelain=v1 --untracked-files=no -- .
) ]]; then
    printf 'Artifact validation requires tracked files to match HEAD exactly.\n' >&2
    exit 1
fi

# Keep the public input scope aligned with _artifact_evidence.py.
CANDIDATE_COMMIT=$(git -C "$REPO_ROOT" rev-list --max-count=1 'HEAD^{commit}' -- \
    ':(top,glob)*' \
    ':(top,glob).github/**' \
    ':(top,glob)docs/*.md' \
    ':(top,glob)examples/**' \
    ':(top,glob)scripts/**' \
    ':(top,glob)src/**' \
    ':(top,glob)tests/**')
STATUS='RUNNING'
mkdir -p -- "$(dirname -- "$RESULTS_FILE")"
REPORT_ENABLED=1
write_report

STAGE='required tool preflight'
require_module anyio dev-python/anyio
require_module hatchling dev-python/hatchling
require_module httpx2 dev-python/httpx2
require_module installer dev-python/installer
require_module pytest dev-python/pytest
require_module urllib3 dev-python/urllib3
python -c "import anyio, hatchling, httpx2, installer, pytest, urllib3; print('artifact tools OK')"

PYTHON_VERSION=$(python -c 'import platform; print(platform.python_version())')
ANYIO_VERSION=$(distribution_version anyio)
HATCHLING_VERSION=$(distribution_version hatchling)
HTTPX2_VERSION=$(distribution_version httpx2)
INSTALLER_VERSION=$(distribution_version installer)
PYTEST_VERSION=$(distribution_version pytest)
URLLIB3_VERSION=$(distribution_version urllib3)
record_check 'PASS' 'Required tool preflight'

STAGE='disposable workspace creation'
WORK_ROOT=$(mktemp -d "${TMPDIR:-/tmp}/sg-python-api-artifacts.XXXXXX")
EXPORT_ROOT="$WORK_ROOT/export"
ARTIFACT_DIR="$WORK_ROOT/artifacts"
SDIST_ROOT="$WORK_ROOT/sdist"
SDIST_WHEEL_DIR="$WORK_ROOT/sdist-wheel"
RUN_ROOT="$WORK_ROOT/run"
mkdir -p "$EXPORT_ROOT" "$ARTIFACT_DIR" "$SDIST_ROOT" "$SDIST_WHEEL_DIR" "$RUN_ROOT"
record_check 'PASS' 'Disposable workspace creation'

STAGE='exact candidate commit export'
git -C "$REPO_ROOT" archive --format=tar --output="$WORK_ROOT/candidate.tar" \
    "$CANDIDATE_COMMIT"
python -m tarfile -e "$WORK_ROOT/candidate.tar" "$EXPORT_ROOT"
record_check 'PASS' 'Exact candidate commit export'

STAGE='source wheel and sdist build'
(
    cd "$EXPORT_ROOT"
    python -m hatchling build -t wheel -t sdist -d "$ARTIFACT_DIR"
)

shopt -s nullglob
source_wheels=("$ARTIFACT_DIR"/*.whl)
sdists=("$ARTIFACT_DIR"/*.tar.gz)
if [[ ${#source_wheels[@]} -ne 1 || ${#sdists[@]} -ne 1 ]]; then
    printf 'Expected exactly one source wheel and one source distribution.\n' >&2
    exit 1
fi
SOURCE_WHEEL=${source_wheels[0]}
SDIST=${sdists[0]}
record_check 'PASS' 'Source wheel and source distribution build'

STAGE='raw sdist contract validation'
python -I "$EXPORT_ROOT/scripts/_sdist_contract.py" \
    "$EXPORT_ROOT" \
    "$SDIST"
record_check 'PASS' 'Raw sdist contract validation'

STAGE='sdist extraction and wheel build'
python -m tarfile -e "$SDIST" "$SDIST_ROOT"
sdist_roots=("$SDIST_ROOT"/*)
if [[ ${#sdist_roots[@]} -ne 1 || ! -d ${sdist_roots[0]} ]]; then
    printf 'Expected the sdist to extract to exactly one source directory.\n' >&2
    exit 1
fi
(
    cd "${sdist_roots[0]}"
    python -m hatchling build -t wheel -d "$SDIST_WHEEL_DIR"
)
sdist_wheels=("$SDIST_WHEEL_DIR"/*.whl)
if [[ ${#sdist_wheels[@]} -ne 1 ]]; then
    printf 'Expected exactly one sdist-derived wheel.\n' >&2
    exit 1
fi
SDIST_WHEEL=${sdist_wheels[0]}
record_check 'PASS' 'Sdist extraction and sdist-derived wheel build'

STAGE='artifact name, content, hash parity, and metadata validation'
python -I "$EXPORT_ROOT/scripts/_sdist_contract.py" --artifacts \
    "$SOURCE_WHEEL" "$SDIST" "$SDIST_WHEEL" "$EXPORT_ROOT"
record_check 'PASS' 'Artifact names, contents, hashes, exclusions, and metadata'

ARTIFACT_NAME=$(basename "$SOURCE_WHEEL")
ARTIFACT_SHA256=$(sha256_file "$SOURCE_WHEEL")
SDIST_NAME=$(basename "$SDIST")
SDIST_SHA256=$(sha256_file "$SDIST")
SDIST_WHEEL_NAME=$(basename "$SDIST_WHEEL")
SDIST_WHEEL_SHA256=$(sha256_file "$SDIST_WHEEL")
write_report

STAGE='source wheel installation'
SOURCE_TARGET="$WORK_ROOT/source-target"
python -m installer --prefix "$SOURCE_TARGET" --no-compile-bytecode "$SOURCE_WHEEL"
record_check 'PASS' 'Source wheel installation'

STAGE='source wheel base installed tests'
TARGET_PREFIX=$SOURCE_TARGET
(
    cd "$RUN_ROOT"
    python -I "$REPO_ROOT/scripts/run_installed_tests.py" "$TARGET_PREFIX" \
        "$REPO_ROOT/tests" base
)
record_check 'PASS' 'Source wheel base installed tests'

STAGE='source wheel async installed tests'
(
    cd "$RUN_ROOT"
    python -I "$REPO_ROOT/scripts/run_installed_tests.py" "$TARGET_PREFIX" \
        "$REPO_ROOT/tests" async
)
record_check 'PASS' 'Source wheel async installed tests'

STAGE='sdist-derived wheel installation'
SDIST_TARGET="$WORK_ROOT/sdist-target"
python -m installer --prefix "$SDIST_TARGET" --no-compile-bytecode "$SDIST_WHEEL"
record_check 'PASS' 'Sdist-derived wheel installation'

STAGE='sdist-derived wheel base installed tests'
TARGET_PREFIX=$SDIST_TARGET
(
    cd "$RUN_ROOT"
    python -I "$REPO_ROOT/scripts/run_installed_tests.py" "$TARGET_PREFIX" \
        "$REPO_ROOT/tests" base
)
record_check 'PASS' 'Sdist-derived wheel base installed tests'

STAGE='sdist-derived wheel async installed tests'
(
    cd "$RUN_ROOT"
    python -I "$REPO_ROOT/scripts/run_installed_tests.py" "$TARGET_PREFIX" \
        "$REPO_ROOT/tests" async
)
record_check 'PASS' 'Sdist-derived wheel async installed tests'

STAGE='validated artifact preservation'
if [[ -e $OUTPUT_ROOT || -L $OUTPUT_ROOT ]]; then
    printf 'Artifact output path already exists: %s\n' "$OUTPUT_ROOT" >&2
    exit 1
fi
mkdir -p -- "$(dirname -- "$OUTPUT_ROOT")"
mkdir -- "$OUTPUT_ROOT"
OUTPUT_CREATED=1
mkdir -- "$OUTPUT_ROOT/source" "$OUTPUT_ROOT/from-sdist"
source_wheel_output="$OUTPUT_ROOT/source/$ARTIFACT_NAME"
source_sdist_output="$OUTPUT_ROOT/source/$SDIST_NAME"
sdist_wheel_output="$OUTPUT_ROOT/from-sdist/$SDIST_WHEEL_NAME"
cp -- "$SOURCE_WHEEL" "$source_wheel_output"
cp -- "$SDIST" "$source_sdist_output"
cp -- "$SDIST_WHEEL" "$sdist_wheel_output"
PRESERVED_SOURCE_WHEEL_PATH=$(report_artifact_path "$source_wheel_output")
PRESERVED_SDIST_PATH=$(report_artifact_path "$source_sdist_output")
PRESERVED_SDIST_WHEEL_PATH=$(report_artifact_path "$sdist_wheel_output")
record_check 'PASS' 'Validated artifact preservation'

STAGE='artifact validation completion'
STATUS='PASS'
